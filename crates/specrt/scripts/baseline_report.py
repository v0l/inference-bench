import argparse
import glob
import json
import os
import re

MODES = ["mtp", "nomtp"]
KVS = [("fp8", ""), ("f16", "f16-")]
HEADING = "## specrt against vLLM on the same harness"


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


def fmt(v, digits=1):
    if v is None:
        return "not run"
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    return f"{v:.{digits}f}"


def ratio(ours, theirs, lower_better=False):
    if ours is None or theirs is None or ours == 0 or theirs == 0:
        return ""
    r = theirs / ours if lower_better else ours / theirs
    return f"{r:.2f}x"


def points(doc, key):
    if not doc:
        return {}
    return {p[key]: p for p in doc["points"]}


def ours(d, suite, kvp, mode):
    return load(os.path.join(d, f"specrt-{suite}-{kvp}{mode}.json"))


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def columns(header_point, metric):
    h = [header_point, "vLLM"]
    for kv, _ in KVS:
        h += [f"specrt {kv} KV", "ratio"]
    return h


def suite_rows(d, suite, mode, key, value, digits=1, lower_better=False, label=str):
    theirs = points(load(os.path.join(d, f"{suite}-{mode}.json")), key)
    mine = [points(ours(d, suite, kvp, mode), key) for _, kvp in KVS]
    keys = sorted(set(theirs) | {k for m in mine for k in m})
    rows = []
    for k in keys:
        t = value(theirs[k]) if k in theirs else None
        row = [label(k), fmt(t, digits)]
        for m in mine:
            o = value(m[k]) if k in m else None
            row += [fmt(o, digits), ratio(o, t, lower_better)]
        rows.append(row)
    return rows


def vllm_acceptance(d, mode, k=2):
    path = os.path.join(d, f"vllm-{mode}.log")
    if not os.path.exists(path):
        return None
    acc = drafted = 0
    with open(path, errors="replace") as f:
        for line in f:
            m = re.search(r"Accepted: (\d+) tokens, Drafted: (\d+) tokens", line)
            if m:
                acc += int(m.group(1))
                drafted += int(m.group(2))
    if drafted == 0:
        return None
    return 1 + acc / (drafted / k)


def run_lines(d):
    out = []
    for path in sorted(glob.glob(os.path.join(d, "specrt-run-*.json"))):
        r = load(path)
        k = r.get("draft_tokens", 2)
        acc = f"{1 + r['spec_accepted'] / (r['spec_drafted'] / k):.2f}" if r.get("spec_drafted") else "n/a"
        out.append(
            f"- `{r['label']}`: {r['started']} to {r['finished']}, commit {r['commit']}"
            f"{' (with ' + str(r['dirty_files']) + ' changed files)' if r.get('dirty_files') else ''}, spec `{r['spec']}`, "
            f"KV {r['kv_dtype']} {r['kv_cache_gb']} GB {r.get('kv_layout', '')}, load {r['load_s']} s, "
            f"mean acceptance length {acc} (drafted {r['spec_drafted']}, accepted {r['spec_accepted']}), "
            f"GPU before `{r['gpu_before']}`, loaded `{r['gpu_loaded']}`"
        )
    return out


def report(d):
    out = [HEADING, ""]
    out.append(
        "Generated by `python3 crates/specrt/scripts/baseline_report.py docs/qwen27-run` from the JSON files only. "
        "vLLM is the committed 10 Nov run; specrt is `crates/specrt/scripts/specrt_baseline.sh` on GPU1 with the same "
        "`vllm_baseline.py` suites. Ratio is specrt over vLLM for rates and vLLM over specrt for times, so above 1 means specrt is ahead."
    )
    out.append("")
    lines = run_lines(d)
    if lines:
        out += ["Runs (card state is `index, memory.used, utilization.gpu, clocks.sm`):", ""] + lines + [""]
    for mode in MODES:
        a = vllm_acceptance(d, mode)
        if a is not None:
            out += [f"vLLM `{mode}` mean acceptance length over its whole run (from `vllm-{mode}.log`): {a:.2f}", ""]
    for mode in MODES:
        out += [f"### Single stream, 128 output tokens, {mode}", ""]
        for title, value, digits, lower in [
            ("decode tok/s", lambda p: p.get("median_decode_tok_s"), 1, False),
            ("prefill tok/s", lambda p: p.get("median_prefill_tok_s"), 0, False),
            ("TTFT s", lambda p: p.get("median_ttft_s"), 3, True),
        ]:
            out += [f"{title}:", ""]
            out += table(suite_rows(d, "single", mode, "prompt_len", value, digits, lower, lambda k: f"{k:,}"), columns("prompt tokens", title))
            out.append("")
        out += [f"### Concurrency, 128 token prompts, aggregate decode tok/s, {mode}", ""]
        out += table(suite_rows(d, "concurrent", mode, "concurrent", lambda p: p.get("aggregate_decode_tok_s")), columns("streams", ""))
        out += ["", f"Median TTFT s at the same points, {mode}:", ""]
        out += table(suite_rows(d, "concurrent", mode, "concurrent", lambda p: p.get("median_ttft_s"), 3, True), columns("streams", ""))
        out.append("")
        if load(os.path.join(d, f"concurrent64k-{mode}.json")):
            out += [f"### 4 streams at 65,536 tokens, aggregate decode tok/s, {mode}", ""]
            out += table(suite_rows(d, "concurrent64k", mode, "concurrent", lambda p: p.get("aggregate_decode_tok_s")), columns("streams", ""))
            out.append("")
        out += [f"### Prefix cache, cold and warm TTFT s, {mode}", ""]
        out += table(suite_rows(d, "prefix", mode, "prompt_len", lambda p: p["cold"]["ttft_s"], 2, True, lambda k: f"{k:,} cold"), columns("prompt", ""))
        out += table(suite_rows(d, "prefix", mode, "prompt_len", lambda p: p.get("median_warm_ttft_s"), 2, True, lambda k: f"{k:,} warm"), columns("prompt", ""))[2:]
        out += ["", f"### Decode of 512 tokens after a held prefix, tok/s, {mode}", ""]
        out += table(suite_rows(d, "held", mode, "prompt_len", lambda p: p.get("median_decode_tok_s"), 1, False, lambda k: f"{k:,}"), columns("held prefix", ""))
        out.append("")
    return "\n".join(out)


def update_doc(doc, text):
    with open(doc) as f:
        body = f.read()
    start = body.find(HEADING)
    if start < 0:
        body = body.rstrip("\n") + "\n\n" + text + "\n"
    else:
        nxt = body.find("\n## ", start + len(HEADING))
        tail = body[nxt + 1 :] if nxt >= 0 else ""
        body = body[:start] + text + "\n" + ("\n" + tail if tail else "")
    with open(doc, "w") as f:
        f.write(body)


def main():
    ap = argparse.ArgumentParser(description="specrt and vLLM side by side from the baseline JSON files")
    ap.add_argument("dir")
    ap.add_argument("--update-doc")
    a = ap.parse_args()
    text = report(a.dir)
    print(text)
    if a.update_doc:
        update_doc(a.update_doc, text)


if __name__ == "__main__":
    main()
