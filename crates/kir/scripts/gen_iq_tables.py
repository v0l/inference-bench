import re
import sys

src = open(sys.argv[1]).read()
tables = {}
for m in re.finditer(r"GGML_TABLE_BEGIN\((\w+), (\w+), (\w+)\)(.*?)GGML_TABLE_END", src, re.S):
    ty, name, _, body = m.groups()
    if name in tables:
        continue
    vals = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
    tables[name] = (ty, vals)

wanted = [
    ("ksigns_iq2xs", "KSIGNS_IQ2XS", "u8"),
    ("iq2xxs_grid", "IQ2XXS_GRID", "u64"),
    ("iq2xs_grid", "IQ2XS_GRID", "u64"),
    ("iq2s_grid", "IQ2S_GRID", "u64"),
    ("iq3xxs_grid", "IQ3XXS_GRID", "u32"),
    ("iq3s_grid", "IQ3S_GRID", "u32"),
    ("kvalues_iq4nl", "KVALUES_IQ4NL", "i8"),
    ("iq1s_grid", "IQ1S_GRID", "u64"),
]
out = ["// Generated by scripts/gen_iq_tables.py from ggml-common.h (MIT, llama.cpp).\n"]
for cname, rname, rty in wanted:
    ty, vals = tables[cname]
    out.append(f"pub const {rname}: [{rty}; {len(vals)}] = [\n")
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(vals[i : i + 8]) + ",\n")
    out.append("];\n\n")
open(sys.argv[2], "w").write("".join(out))
